export function listCameraDrivers(): CameraDriverDescriptor[] {
  return Object.values(CAMERA_DRIVERS);
}

export function getCameraDriver(driverId?: string | null): CameraDriverDescriptor {
  if (driverId && driverId in CAMERA_DRIVERS) {
    return CAMERA_DRIVERS[driverId as CameraDriverId];
  }
  return CAMERA_DRIVERS.standard_onvif;
}

export function getDriverCapabilities(driverId?: string | null): CameraCapabilityMatrix {
  return getCameraDriver(driverId).capabilities;
}

export function renderDriverUri(
  template: string,
  host: string,
  rtspPort = 554,
  controlPort = 80,
  channel = 1
): string {
  return template
    .replace(/\{host\}/g, host)
    .replace(/\{rtsp_port\}/g, String(rtspPort))
    .replace(/\{control_port\}/g, String(controlPort))
    .replace(/\{channel\}/g, String(channel));
}
